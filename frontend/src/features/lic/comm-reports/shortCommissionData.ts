export type ShortCommissionSortingOption = "policy-wise" | "bill-wise";

export interface ShortCommissionFormData {
  dataFilters: Array<{ type: string; id: string; name: string }>; // Agencies
  reportDate: string; // e.g. "01/Sep/2026"
  ignoreDifferenceOf: number; // e.g. 0
  sortingOption: ShortCommissionSortingOption; // "policy-wise" | "bill-wise"
  selectedPolicyIds?: string[];
  selectedBills?: string[];
}

export interface ShortCommissionItem {
  id: string;
  policyNo: string; // e.g. "906760717"
  agCd: string; // e.g. "J"
  groupCode: string; // e.g. "B106"
  holderName: string; // e.g. "Babariya Kinjal"
  dueDate: string; // e.g. "02/22"
  premiumAmount: number; // e.g. 76121.00
  planTermPpt: string; // e.g. "836/25/16"
  billDate: string; // e.g. "02/221"
  comsnRecble: number; // e.g. 3806.05
  comsnRecvd: number; // e.g. 3989.65
  netRecble: number; // e.g. -183.60
  comRate: number; // e.g. 5.00
}

export interface ShortCommissionTotals {
  totalCount: number;
  totalPremium: number;
  totalComsnRecble: number;
  totalComsnRecvd: number;
  totalNetRecble: number;
}

/**
 * Format net receivable: if negative, wrap in parentheses (e.g. (183.60)), otherwise standard 2 decimal places.
 */
export function formatNetReceivable(val: number): string {
  if (val < -0.001) {
    return `(${Math.abs(val).toFixed(2)})`;
  }
  return val.toFixed(2);
}

/**
 * Calculate totals for short/excess commissions
 */
export function calculateShortCommissionTotals(items: ShortCommissionItem[]): ShortCommissionTotals {
  let totalPremium = 0;
  let totalComsnRecble = 0;
  let totalComsnRecvd = 0;
  let totalNetRecble = 0;

  items.forEach((item) => {
    totalPremium += item.premiumAmount;
    totalComsnRecble += item.comsnRecble;
    totalComsnRecvd += item.comsnRecvd;
    totalNetRecble += item.netRecble;
  });

  return {
    totalCount: items.length,
    totalPremium: Math.round(totalPremium * 100) / 100,
    totalComsnRecble: Math.round(totalComsnRecble * 100) / 100,
    totalComsnRecvd: Math.round(totalComsnRecvd * 100) / 100,
    totalNetRecble: Math.round(totalNetRecble * 100) / 100,
  };
}

