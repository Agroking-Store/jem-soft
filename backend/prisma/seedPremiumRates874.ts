/** [minSumAssured, maxSumAssured]; rebate value is from the official age/maturity table.
 *  Four slabs per LIC's official circular:
 *    Slab 1 : ₹3,50,000 – ₹4,75,000
 *    Slab 2 : ₹5,00,000 – ₹9,75,000
 *    Slab 3 : ₹10,00,000 – ₹24,50,000
 *    Slab 4 : ₹25,00,000 and above
 */
const SA_REBATE_SLABS: [number, number | null][] = [
  [350000, 475000],
  [500000, 975000],
  [1000000, 2450000],
  [2500000, null],
];

const MODE_FACTORS: [string, number][] = [
  ["Yearly", 1.000000],
  ["Half-Yearly", 0.509000],
  ["Quarterly", 0.256800],
  ["Monthly", 0.086100],
];

const rateRows = RATE_GRID.flatMap(([entryAge, policyTerm, premiumPayingTerm, option, tabularRate]) =>
  [null, entryAge * 2, entryAge * 2 + 1].map((ageBand) => ({
    entryAge,
    ageBand,
    policyTerm,
    premiumPayingTerm,
    option,
    tabularRate,
  })),
);

function rebatesFor(entryAge: number, maturityAge: number): number[] {
  // LIC circular: four SA slabs, two entry-age bands (≤9 / 10-13) and two
  // maturity-age bands (18-21 / 22-25).
  //
  // Slab order must match SA_REBATE_SLABS above:
  //   [slab1: 3.5L-4.75L,  slab2: 5L-9.75L,  slab3: 10L-24.5L,  slab4: 25L+]
  if (entryAge <= 9)
    return maturityAge <= 21
      ? [2.60, 4.55, 6.80, 8.20]
      : [2.85, 5.55, 8.35, 10.00];
  return maturityAge <= 21
    ? [2.60, 4.55, 6.80, 8.20]
    : [2.60, 4.55, 6.85, 8.20];
}

function buildRebateRows() {
  const rows: Record<string, unknown>[] = [];
  for (let entryAge = 0; entryAge <= 13; entryAge++) {
    for (let policyTerm = 10; policyTerm <= 25; policyTerm++) {
      const maturityAge = entryAge + policyTerm;
      if (maturityAge < 18 || maturityAge > 25) continue;
      const rebates = rebatesFor(entryAge, maturityAge);
      for (const ageBand of [null, entryAge * 2, entryAge * 2 + 1]) {
        SA_REBATE_SLABS.forEach(([minSumAssured, maxSumAssured], i) => {
          rows.push({
            entryAge,
            ageBand,
            policyTerm,
            minSumAssured,
            maxSumAssured,
            rebatePerThousand: Number(rebates[i]!.toFixed(4)),
          });
        });
      }
    }
  }
  return rows;
}

export const seedPremiumRates874 = async (prisma: PrismaClient) => {
  const product = await prisma.productMaster.findFirst({
    where: { planNumber: PLAN_NUMBER },
    select: { id: true, productName: true },
  });
  if (!product) {
    console.log("  x Plan " + PLAN_NUMBER + " not found");
    return;
  }

  console.log("  - Plan " + PLAN_NUMBER + " (" + product.productName + ") premium rates");
  await prisma.productPremiumRate.deleteMany({ where: { productId: product.id } });
  await prisma.productPremiumRate.createMany({
    data: rateRows.map((r) => ({ productId: product.id, ...r })),
  });

  const rebateRows = buildRebateRows();
  await prisma.productAgeTermRebate.deleteMany({ where: { productId: product.id } });
  await prisma.productAgeTermRebate.createMany({
    data: rebateRows.map((r) => ({ productId: product.id, ...r })) as never,
  });

  console.log("      " + rateRows.length + " rates, " + rebateRows.length + " rebates");
};

