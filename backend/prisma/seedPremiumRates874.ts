export const seedModeFactors874 = async (prisma: PrismaClient) => {
  const product = await prisma.productMaster.findFirst({
    where: { planNumber: PLAN_NUMBER },
    select: { id: true },
  });
  if (!product) return;

  const modes = await prisma.premiumModeMaster.findMany({
    where: { modeName: { in: MODE_FACTORS.map(([name]) => name) } },
    select: { id: true, modeName: true },
  });
  for (const mode of modes) {
    const factor = MODE_FACTORS.find(([name]) => name === mode.modeName)?.[1];
    if (factor === undefined) continue;
    await prisma.productPremiumModeFactor.upsert({
      where: { productId_premiumModeId: { productId: product.id, premiumModeId: mode.id } },
      update: { factor },
      create: { productId: product.id, premiumModeId: mode.id, factor },
    });
  }
  console.log("      " + modes.length + " mode factors");
};
