export const seedPremiumRates917 = async (prisma: PrismaClient) => {
  const product = await prisma.productMaster.findFirst({
    where: { planNumber: PLAN_NUMBER, productCode: { startsWith: "LEGACY-" } },
    select: { id: true, productName: true },
  });
  if (!product) {
    console.log(`  x Plan ${PLAN_NUMBER} not found`);
    return;
  }
  console.log(`  - Plan ${PLAN_NUMBER} (${product.productName}) premium rates`);

  await prisma.productPremiumRate.deleteMany({ where: { productId: product.id } });
  await prisma.productPremiumRate.createMany({
    data: RATE_ROWS.map(([entryAge, ageBand, policyTerm, premiumPayingTerm, tabularRate]) => ({
      productId: product.id,
      entryAge,
      ageBand,
      policyTerm,
      premiumPayingTerm,
      tabularRate,
    })),
  });

  await prisma.productSumAssuredRebate.deleteMany({ where: { productId: product.id } });
  await prisma.productSumAssuredRebate.createMany({
    data: SA_REBATE_ROWS.map(([minSumAssured, maxSumAssured, rebatePerThousand]) => ({
      productId: product.id,
      minSumAssured,
      maxSumAssured,
      rebatePerThousand,
    })),
  });

  // Catalogue facts the sheet did not carry.
  const masters = await prisma.productAttributeMaster.findMany({
    where: { attributeCode: { in: ATTRIBUTES.map(([code]) => code) } },
    select: { id: true, attributeCode: true },
  });
  for (const [code, value] of ATTRIBUTES) {
    const master = masters.find((m) => m.attributeCode === code);
    if (!master) continue;
    await prisma.productAttributeValue.upsert({
      where: {
        productId_attributeId: { productId: product.id, attributeId: master.id },
      },
      update: { value },
      create: { productId: product.id, attributeId: master.id, value },
    });
  }

  console.log(`      ${RATE_ROWS.length} rates, ${SA_REBATE_ROWS.length} rebate slabs`);
};

export const seedRiderPremium917 = async (prisma: PrismaClient) => {
  const product = await prisma.productMaster.findFirst({
    where: { planNumber: PLAN_NUMBER, productCode: { startsWith: "LEGACY-" } },
    select: { id: true },
  });
  if (!product) return;

  const riders = await prisma.riderMaster.findMany({
    where: { riderCode: { in: ["DAB", "TRB"] } },
    select: { id: true, riderCode: true },
  });
  const idByCode = new Map(riders.map((r) => [r.riderCode, r.id]));

  const rows = [
    ...DAB_ROWS.filter(() => idByCode.has("DAB")).map(([entryAge, ageBand, riderTerm, ratePerThousand]) => ({
      productId: product.id,
      riderId: idByCode.get("DAB")!,
      entryAge,
      ageBand,
      riderTerm,
      premiumPayingTerm: 1,
      ratePerThousand,
    })),
    ...TRB_RATES.filter(() => idByCode.has("TRB")).map(([entryAge, ageBand, riderTerm, ratePerThousand]) => ({
      productId: product.id,
      riderId: idByCode.get("TRB")!,
      entryAge,
      ageBand,
      riderTerm,
      premiumPayingTerm: 1,
      ratePerThousand,
    })),
  ];

  await prisma.productRider.deleteMany({ where: { productId: product.id } });
  await prisma.riderPremiumRate.deleteMany({ where: { productId: product.id } });
  await prisma.riderPremiumRate.createMany({ data: rows });
  await prisma.productRider.createMany({
    data: [...idByCode.values()].map((riderId) => ({ productId: product.id, riderId })),
    skipDuplicates: true,
  });

  console.log(`      ${rows.length} rider rates (DAB ${DAB_ROWS.length}, TRB ${TRB_RATES.length})`);
};

