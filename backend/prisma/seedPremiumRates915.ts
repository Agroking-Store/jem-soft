export const seedPremiumRates915 = async (prisma: PrismaClient) => {
  const product = await prisma.productMaster.findFirst({
    where: { planNumber: PLAN_NUMBER, productCode: { startsWith: "LEGACY-" } },
    select: { id: true, productName: true },
  });
  if (!product) {
    console.log(`  x Plan ${PLAN_NUMBER} not found`);
    return;
  }
  console.log(`  - Plan ${PLAN_NUMBER} (${product.productName}) premium rates`);

  if (product.productName !== "LIC's New Jeevan Anand") {
    await prisma.productMaster.update({
      where: { id: product.id },
      data: { productName: "LIC's New Jeevan Anand" },
    });
  }

  await prisma.productPremiumRate.deleteMany({ where: { productId: product.id } });
  await prisma.productPremiumRate.createMany({
    data: RATE_ROWS.map(([entryAge, policyTerm, tabularRate]) => ({
      productId: product.id,
      entryAge,
      ageBand: null,
      policyTerm,
      premiumPayingTerm: policyTerm,
      tabularRate,
    })),
  });

  await prisma.productSumAssuredRebate.deleteMany({ where: { productId: product.id } });
  await prisma.productSumAssuredRebate.createMany({
    data: SA_REBATE_ROWS.map(([minSumAssured, maxSumAssured, rebatePerThousand]) => ({
      productId: product.id,
      minSumAssured,
      maxSumAssured,
      rebatePerThousand,
    })),
  });

  const masters = await prisma.productAttributeMaster.findMany({
    where: { attributeCode: { in: ATTRIBUTES.map(([code]) => code) } },
    select: { id: true, attributeCode: true },
  });
  for (const [code, value] of ATTRIBUTES) {
    const master = masters.find((m) => m.attributeCode === code);
    if (!master) continue;
    await prisma.productAttributeValue.upsert({
      where: {
        productId_attributeId: { productId: product.id, attributeId: master.id },
      },
      update: { value },
      create: { productId: product.id, attributeId: master.id, value },
    });
  }

  console.log(`      ${RATE_ROWS.length} rates, ${SA_REBATE_ROWS.length} rebate slabs`);
};

export const seedRiderPremium915 = async (prisma: PrismaClient) => {
  const product = await prisma.productMaster.findFirst({
    where: { planNumber: PLAN_NUMBER, productCode: { startsWith: "LEGACY-" } },
    select: { id: true },
  });
  if (!product) return;

  const riders = await prisma.riderMaster.findMany({
    where: { riderCode: { in: ["DAB", "TRB", "CIR"] } },
    select: { id: true, riderCode: true },
  });
  const idByCode = new Map(riders.map((r) => [r.riderCode, r.id]));

  const rows: any[] = [];
  if (idByCode.has("DAB")) {
    rows.push(
      ...DAB_ROWS.map(([entryAge, riderTerm]) => ({
        productId: product.id,
        riderId: idByCode.get("DAB")!,
        entryAge,
        ageBand: null,
        riderTerm,
        premiumPayingTerm: null,
        ratePerThousand: 1,
      })),
    );
  }
  if (idByCode.has("TRB")) {
    rows.push(
      ...TRB_ROWS.map(([entryAge, riderTerm, ratePerThousand]) => ({
        productId: product.id,
        riderId: idByCode.get("TRB")!,
        entryAge,
        ageBand: null,
        riderTerm,
        premiumPayingTerm: null,
        ratePerThousand,
      })),
    );
  }
  if (idByCode.has("CIR")) {
    rows.push(
      ...CIR_ROWS.map(([entryAge, riderTerm, gender, ratePerThousand]) => ({
        productId: product.id,
        riderId: idByCode.get("CIR")!,
        entryAge,
        ageBand: null,
        riderTerm,
        premiumPayingTerm: null,
        gender,
        ratePerThousand,
      })),
    );
  }

  await prisma.productRider.deleteMany({ where: { productId: product.id } });
  await prisma.riderPremiumRate.deleteMany({ where: { productId: product.id } });
  await prisma.riderPremiumRate.createMany({ data: rows });
  await prisma.productRider.createMany({
    data: [...idByCode.values()].map((riderId) => ({
      productId: product.id,
      riderId,
    })),
    skipDuplicates: true,
  });

  console.log(
    `      ${rows.length} rider rates (DAB ${DAB_ROWS.length}, TRB ${TRB_ROWS.length}, CIR ${CIR_ROWS.length})`,
  );
};

export const seedModeFactors915 = async (prisma: PrismaClient) => {
  const product = await prisma.productMaster.findFirst({
    where: { planNumber: PLAN_NUMBER, productCode: { startsWith: "LEGACY-" } },
    select: { id: true },
  });
  if (!product) return;

  const modes = await prisma.premiumModeMaster.findMany({
    where: { modeName: { in: MODE_FACTORS.map((m) => m[0]) } },
    select: { id: true, modeName: true },
  });

  for (const mode of modes) {
    const factor = MODE_FACTORS.find((m) => m[0] === mode.modeName)?.[1];
    if (factor === undefined) continue;
    await prisma.productPremiumModeFactor.upsert({
      where: {
        productId_premiumModeId: { productId: product.id, premiumModeId: mode.id },
      },
      update: { factor },
      create: { productId: product.id, premiumModeId: mode.id, factor },
    });
  }
  console.log(`      ${MODE_FACTORS.length} mode factors`);
};
